const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const workerRoot = process.cwd();
const worker = fs.readFileSync(path.join(workerRoot, 'src/index.ts'), 'utf8');
const schema = fs.readFileSync(path.join(workerRoot, 'schema.sql'), 'utf8');
const migration = fs.readFileSync(path.join(workerRoot, 'migrations/0002-first-activation-duration.sql'), 'utf8');
assert.ok(worker.includes('const startsAt = candidate.starts_at ?? now;'), 'new activation starts now while an approved transfer preserves the original start date');
assert.ok(worker.includes('candidate.duration_days'), 'activation must use the stored duration');
assert.ok(worker.includes('candidate.expires_at ?? (durationDays === null ? null : startsAt + durationDays * DAY)'), 'new licenses calculate expiry from first activation while transferred licenses preserve their original expiry');
assert.ok(worker.includes('starts_at = ?, expires_at = ?'), 'activation must persist both dates');
assert.ok(worker.includes('duration_days, starts_at, expires_at'), 'issuance must persist duration separately');
assert.ok(worker.includes('VALUES (?, ?, \'issued\', ?, ?, NULL, NULL, ?, ?)'), 'new codes must have no start or expiry before activation');
assert.ok(worker.includes('duration_days = ?, expires_at = ?'), 'renewal must persist the renewed duration and expiry');
assert.ok(schema.includes('duration_days INTEGER'));
assert.ok(migration.includes('ALTER TABLE licenses ADD COLUMN duration_days INTEGER'));
assert.ok(migration.includes('license_type = \'perpetual\' THEN NULL'));
const DAY = 86400000;
const activatedAt = Date.UTC(2026, 0, 10, 12);
assert.equal(activatedAt + 365 * DAY - activatedAt, 365 * DAY, 'annual validity is exactly 365 days after activation');
const futureExpiry = activatedAt + 400 * DAY;
assert.equal(Math.max(futureExpiry, activatedAt) + 365 * DAY, activatedAt + 765 * DAY, 'renewal extends from the future expiry');
const pastExpiry = activatedAt - DAY;
assert.equal(Math.max(pastExpiry, activatedAt) + 365 * DAY, activatedAt + 365 * DAY, 'renewal after expiry starts from renewal time');
assert.ok(worker.includes('بياناتك محفوظة'), 'expiry response must preserve user data');
assert.ok(!/DELETE FROM (students|attendance|violations|documents)/i.test(worker), 'expiry must never delete user records');
console.log('PASS: first-activation annual term, renewal extension, migration, and non-destructive expiry.');
