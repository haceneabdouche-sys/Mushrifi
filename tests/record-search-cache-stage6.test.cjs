const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('android/app/src/main/assets/index.html','utf8');
const start=html.indexOf('function normalizeDirectorySearch(value){');
const end=html.indexOf('\nlet studentIndexSource',start);
assert.ok(start>=0&&end>start,'search normalizer and weak cache exist');
const sandbox={};vm.createContext(sandbox);
vm.runInContext(html.slice(start,end)+'\nthis.__test={cachedRecordSearchText};',sandbox);
const search=sandbox.__test.cachedRecordSearchText;
const task={type:'حراسة الامتحانات',notes:'ملاحظة أصلية',actionTaken:'إجراء أول'};
assert.ok(search(task,[task.type,task.notes,task.actionTaken]).includes('ملاحظة اصلية'));
const first=search(task,[task.type,task.notes,task.actionTaken]);
assert.equal(search(task,[task.type,task.notes,task.actionTaken]),first,'unchanged data reuses normalized cache');
task.notes='ملاحظة معدلة';
assert.ok(search(task,[task.type,task.notes,task.actionTaken]).includes('ملاحظة معدلة'));
assert.ok(!search(task,[task.type,task.notes,task.actionTaken]).includes('ملاحظة اصلية'),'edited note invalidates cache');
task.actionTaken='نتيجة جديدة';
assert.ok(search(task,[task.type,task.notes,task.actionTaken]).includes('نتيجة جديدة'));
const reception={purpose:'توجيه',actionTaken:'متابعة',studentLabel:'وائل عيسو'};
assert.ok(search(reception,[reception.purpose,reception.actionTaken,reception.studentLabel]).includes('وائل عيسو'));
reception.studentLabel='تلميذ آخر';
assert.ok(search(reception,[reception.purpose,reception.actionTaken,reception.studentLabel]).includes('تلميذ اخر'));
assert.ok(!search(reception,[reception.purpose,reception.actionTaken,reception.studentLabel]).includes('وائل عيسو'),'linked student change invalidates cache');
const audit={summary:'تعديل سجل',changes:[{label:'المدة',before:2,after:4}]};
assert.ok(search(audit,[audit.summary,JSON.stringify(audit.changes)]).includes('المدة'));
audit.changes[0].after=6;
assert.ok(search(audit,[audit.summary,JSON.stringify(audit.changes)]).includes('6'),'audit change updates cache');
assert.ok(html.includes('cachedRecordSearchText(item,[item.type,item.date,item.period,item.location,item.section,item.notes,item.actionTaken])'));
assert.ok(html.includes('cachedRecordSearchText(item,[item.date,item.time,item.visitorType,item.purpose,item.status,item.nextDate,item.actionTaken,guardianReceptionStudentLabel(item.student)])'));
assert.ok(html.includes('cachedRecordSearchText(entry,[hay])'));
assert.ok(html.includes('const AUDIT_LOG_LIMIT=500;'));
console.log('PASS: Stage 6 record-search cache refresh and audit privacy/limit assertions.');
